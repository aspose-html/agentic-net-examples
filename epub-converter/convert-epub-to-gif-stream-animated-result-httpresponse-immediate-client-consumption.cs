// Convert EPUB to GIF and stream the animated result through an HttpResponse for immediate client consumption.

using System;
using System.IO;
using System.Collections.Generic;
using System.Net.Http;
using System.Net.Http.Headers;
using Aspose.Html.IO;

public class MemoryStreamProvider : ICreateStreamProvider, IDisposable
{
    private readonly List<MemoryStream> _streams = new List<MemoryStream>();

    public Stream GetStream(string name, string extension)
    {
        return GetStream(name, extension, 0);
    }

    public Stream GetStream(string name, string extension, int page)
    {
        var ms = new MemoryStream();
        _streams.Add(ms);
        return ms;
    }

    public void ReleaseStream(Stream stream)
    {
        // No action needed for in-memory streams
    }

    public void Dispose()
    {
        foreach (var s in _streams)
        {
            s.Dispose();
        }
    }

    public IReadOnlyList<MemoryStream> Streams => _streams;
}

class Program
{
    static void Main()
    {
        try
        {
            // Prepare a dummy EPUB file (in a real scenario, provide a valid EPUB)
            string epubPath = "sample.epub";
            if (!File.Exists(epubPath))
            {
                File.WriteAllBytes(epubPath, new byte[0]);
            }

            using (FileStream epubStream = File.OpenRead(epubPath))
            {
                var options = new Aspose.Html.Saving.ImageSaveOptions(Aspose.Html.Rendering.Image.ImageFormat.Gif);
                using (var provider = new MemoryStreamProvider())
                {
                    Aspose.Html.Converters.Converter.ConvertEPUB(epubStream, options, provider);

                    if (provider.Streams.Count > 0)
                    {
                        var gifStream = provider.Streams[0];
                        gifStream.Position = 0;
                        byte[] gifBytes = gifStream.ToArray();

                        var response = new HttpResponseMessage(System.Net.HttpStatusCode.OK);
                        response.Content = new ByteArrayContent(gifBytes);
                        response.Content.Headers.ContentType = new MediaTypeHeaderValue("image/gif");

                        Console.WriteLine($"Conversion successful. GIF size: {gifBytes.Length} bytes.");
                        Console.WriteLine("Simulated HTTP response prepared with Content-Type: image/gif.");
                    }
                    else
                    {
                        Console.WriteLine("No GIF was generated by the conversion process.");
                    }
                }
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"Error: {ex.Message}");
        }
    }
}